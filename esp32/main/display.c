int display_wrap(const char *text, char lines[][DISPLAY_LINE_BYTES], int max_lines)
{
    // Word-wraps UTF-8 text to DISPLAY_COLS glyphs per line (a multi-byte letter counts once).
    int n = 0;
    const char *p = text ? text : "";
    while (*p && n < max_lines) {
        while (*p == ' ') {
            p++;
        }
        if (!*p) {
            break;
        }
        const char *start = p, *cut = NULL, *q = p;
        int glyphs = 0;
        while (*q && glyphs < DISPLAY_COLS) {
            if (*q == ' ') {
                cut = q;
            }
            q++;
            while ((*q & 0xC0) == 0x80) {
                q++; // UTF-8 continuation byte
            }
            glyphs++;
        }
        const char *end = (*q && *q != ' ' && cut) ? cut : q;
        size_t len = end - start;
        if (len > DISPLAY_LINE_BYTES - 1) {
            len = DISPLAY_LINE_BYTES - 1;
        }
        memcpy(lines[n], start, len);
        lines[n][len] = '\0';
        n++;
        p = end;
    }
    return n;
}
